"""
Submarket lookup. No third-party dependencies — this runs inside collect.py in
Actions and inside the tests.

submarkets.geojson is generated by build_submarkets.py; see that file for how
the polygons are drawn and buffered, and why they overlap.
"""
from __future__ import annotations

import json
import os
from functools import lru_cache

GEOJSON = os.path.join(os.path.dirname(os.path.abspath(__file__)), "submarkets.geojson")


@lru_cache(maxsize=1)
def _load() -> list[dict]:
    with open(GEOJSON) as fh:
        fc = json.load(fh)
    feats = []
    for f in fc["features"]:
        ring = f["geometry"]["coordinates"][0]
        xs = [c[0] for c in ring]
        ys = [c[1] for c in ring]
        feats.append({
            "id": f["properties"]["id"],
            "hood": f["properties"]["hood"],
            "precedence": f["properties"]["precedence"],
            "ring": ring,
            "bbox": (min(xs), min(ys), max(xs), max(ys)),
        })
    feats.sort(key=lambda f: f["precedence"])
    return feats


def _in_ring(lon: float, lat: float, ring: list) -> bool:
    """Ray casting. Points exactly on an edge are not guaranteed either way."""
    inside = False
    n = len(ring)
    j = n - 1
    for i in range(n):
        xi, yi = ring[i]
        xj, yj = ring[j]
        if (yi > lat) != (yj > lat):
            x_cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x_cross:
                inside = not inside
        j = i
    return inside


def hood_of(lon: float | None, lat: float | None) -> str | None:
    """The tracked submarket id containing this point, or None.

    Polygons overlap; the lowest `precedence` wins (build_submarkets.py).
    """
    if lon is None or lat is None:
        return None
    for f in _load():
        x0, y0, x1, y1 = f["bbox"]
        if not (x0 <= lon <= x1 and y0 <= lat <= y1):
            continue
        if _in_ring(lon, lat, f["ring"]):
            return f["id"]
    return None


def hoods_containing(lon: float, lat: float) -> list[str]:
    """Every submarket whose polygon contains the point, in precedence order."""
    return [f["id"] for f in _load() if _in_ring(lon, lat, f["ring"])]


def hood_label(hood_id: str) -> str:
    for f in _load():
        if f["id"] == hood_id:
            return f["hood"]
    return hood_id


def all_hoods() -> list[str]:
    return [f["id"] for f in _load()]
